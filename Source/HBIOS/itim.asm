;___ITIM______________________________________________________________________________________________________________
;
; MRZ80 INTERVAL TIMER (MISTER FPGA Z80 SYSTEM) - PERIODIC SYSTEM TICK
; MRZ80 HDL: Components/TIMER/IntervalTimer.vhd
;
; THE INTERVAL TIMER COUNTS MILLISECONDS FROM THE FPGA SYSTEM CLOCK (SO IT
; IS INDEPENDENT OF THE CPU CLOCK AND WAIT STATES) AND ASSERTS THE Z80 INT
; PIN EVERY INTERVAL MILLISECONDS.  THE REQUEST IS A LEVEL THAT STAYS ASSERTED
; UNTIL SOFTWARE ACKNOWLEDGES IT.  ONLY USED FOR Z80 INT MODE 1 (RST 38H),
; WHERE THE HBIOS IM1 CALL LIST POLLS EACH HANDLER IN TURN.
;
; THE TIMER RUNS IN AUTO-RESTART MODE, SO IT IS FREE OF ACCUMULATED DRIFT.
; ITS INTERVAL IS A WHOLE NUMBER OF MILLISECONDS, THEREFORE TICKFREQ MUST
; DIVIDE 1000 EXACTLY (10, 20, 25, 40, 50, 100, ...).  60 HZ IS NOT POSSIBLE.
;
; REGISTER MAP (OFFSETS FROM ITIMIO, 0D0H)
;
;  OFFSET | READ         | WRITE
;  -------|--------------|---------------------------------------------
;  +0     | INTERVAL LO  | INTERVAL LOW BYTE (MILLISECONDS)
;  +1     | INTERVAL HI  | INTERVAL HIGH BYTE
;  +2     | STATUS       | CONTROL (EVERY WRITE SETS IE AND AUTO, ACTS ON RUN)
;  +3     | STATUS       | COMMAND (ONE-SHOT STROBES, NOTHING IS STORED)
;
;  CONTROL: BIT 0 RUN (1 = START FROM 0 IF STOPPED, 0 = STOP AND CLEAR)
;           BIT 1 IE (1 = EXPIRED DRIVES INT)
;           BIT 2 AUTO (1 = RESTART ON EXPIRY, 0 = ONE-SHOT)
;  COMMAND: BIT 0 RESET COUNTER, BIT 1 ACK (CLEAR EXPIRED, RELEASES INT),
;           BIT 2 CLEAR OVERFLOW
;  STATUS:  BIT 0 EXPIRED, BIT 1 OVERFLOW (A TICK WAS MISSED, STICKY),
;           BIT 2 RUNNING, BIT 3 INTREQ (EXPIRED AND IE: THIS TIMER IS
;           ASSERTING INT), BIT 4 IE, BIT 5 AUTO, BITS 7:6 ZERO
;
; A Z80 RESET CLEARS THE TIMER, BUT AN HBIOS RESTART IN PLACE DOES NOT, SO
; PREINIT ALWAYS STOPS THE TIMER AND CLEARS ITS STATE BEFORE ANYTHING ELSE.
;______________________________________________________________________________________________________________________
;
#IF (INTMODE != 1)
	.ECHO	"*** ERROR: ITIM TIMER REQUIRES INTMODE 1!!!\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
ITIM_INTERVAL	.EQU	1000 / TICKFREQ		; MILLISECONDS BETWEEN TICKS
;
#IF ((ITIM_INTERVAL * TICKFREQ) != 1000)
	.ECHO	"*** ERROR: ITIM TIMER REQUIRES A TICKFREQ THAT DIVIDES 1000!!!\n"
	!!!	; FORCE AN ASSEMBLY ERROR
#ENDIF
;
ITIM_IO_INTLO	.EQU	ITIMIO + 0		; INTERVAL LOW BYTE (R/W)
ITIM_IO_INTHI	.EQU	ITIMIO + 1		; INTERVAL HIGH BYTE (R/W)
ITIM_IO_CTL	.EQU	ITIMIO + 2		; CONTROL (W) / STATUS (R)
ITIM_IO_CMD	.EQU	ITIMIO + 3		; COMMAND (W) / STATUS (R)
;
ITIM_CTL_RUN	.EQU	%00000001		; CONTROL: RUN
ITIM_CTL_IE	.EQU	%00000010		; CONTROL: INTERRUPT ENABLE
ITIM_CTL_AUTO	.EQU	%00000100		; CONTROL: AUTO RESTART (PERIODIC)
;
ITIM_CMD_ACK	.EQU	%00000010		; COMMAND: ACKNOWLEDGE (CLEAR EXPIRED)
ITIM_CMD_CLROVF	.EQU	%00000100		; COMMAND: CLEAR OVERFLOW
;
ITIM_ST_INTREQ	.EQU	%00001000		; STATUS: THIS TIMER IS ASSERTING INT
;
	DEVECHO	"ITIM: IO="
	DEVECHO	ITIMIO
	DEVECHO	", INTERVAL="
	DEVECHO	ITIM_INTERVAL
	DEVECHO	"MS"
;
	DEVECHO "\n"
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_ITIM	.EQU	$
;
	.DW	SIZ_ITIM		; MODULE SIZE
	.DW	ITIM_INITPHASE		; ADR OF INIT PHASE HANDLER
;
ITIM_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_PREINIT	; PREINIT PHASE?
	JP	Z,ITIM_PREINIT		; DO PREINIT
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,ITIM_INIT		; DO INIT
	RET				; DONE
;
;==================================================================================================
; ITIM PRE-INITIALIZATION
;
; STOP THE TIMER AND CLEAR ANY STATE LEFT BY A PREVIOUS HBIOS RUN, THEN CHECK
; WHETHER THE TIMER EXISTS.  IF IT DOES, HOOK ITS INTERRUPT HANDLER INTO THE
; IM1 CALL LIST.  THE TIMER IS NOT STARTED UNTIL THE INIT PHASE.
;==================================================================================================
;
ITIM_PREINIT:
	XOR	A			; RUN=0, IE=0, AUTO=0
	OUT	(ITIM_IO_CTL),A		; STOP THE TIMER AND CLEAR THE COUNT
	LD	A,ITIM_CMD_ACK | ITIM_CMD_CLROVF
	OUT	(ITIM_IO_CMD),A		; RELEASE ANY PENDING REQUEST
;
	CALL	ITIM_DETECT		; DO WE HAVE ONE?
	LD	(ITIM_EXIST),A		; SAVE IT
	RET	NZ			; ABORT IF NONE
;
	LD	HL,ITIM_INT
	CALL	HB_ADDIM1		; ADD TO IM1 CALL LIST
;
	XOR	A
	RET
;
;==================================================================================================
; DRIVER INITIALIZATION
;==================================================================================================
;
ITIM_INIT:
	; ANNOUNCE PORT
	CALL	NEWLINE			; FORMATTING
	PRTS("ITIM:$")			; FORMATTING
;
	PRTS(" IO=0x$")			; FORMATTING
	LD	A,ITIMIO		; GET BASE PORT
	CALL	PRTHEXBYTE		; PRINT BASE PORT
;
	LD	A,(ITIM_EXIST)		; IS IT THERE?
	OR	A			; 0 MEANS YES
	JR	Z,ITIM_INIT1		; CONTINUE TO ENABLE IT
;
	; NOTIFY NO ITIM HARDWARE
	PRTS(" NOT PRESENT$")
	OR	$FF			; SIGNAL FAILURE
	RET
;
ITIM_INIT1:
	; ANNOUNCE THE TICK RATE
	PRTS(" INTERVAL=$")
	LD	A,ITIM_INTERVAL		; INTERVAL IN MS
	CALL	PRTDECB			; PRINT IT
	PRTS("MS$")
;
	; PROGRAM THE INTERVAL, THEN START THE TIMER PERIODIC WITH INTS ON.
	; RUN STARTS THE COUNT FROM ZERO, SO THE FIRST TICK COMES A FULL
	; INTERVAL LATER.  INTS ARE ALREADY ENABLED AT THIS POINT.
	LD	A,ITIM_INTERVAL & $FF
	OUT	(ITIM_IO_INTLO),A
	LD	A,ITIM_INTERVAL >> 8
	OUT	(ITIM_IO_INTHI),A
	LD	A,ITIM_CTL_RUN | ITIM_CTL_IE | ITIM_CTL_AUTO
	OUT	(ITIM_IO_CTL),A
;
	XOR	A			; SIGNAL SUCCESS
	RET				; DONE
;
;==================================================================================================
; INTERRUPT HANDLER
;
; CALLED FROM THE IM1 CALL LIST.  RETURNS NZ IF THE INTERRUPT WAS HANDLED, ZF
; SET (A=0) IF IT WAS NOT OURS SO THE NEXT HANDLER IN THE LIST GETS A TURN.
;==================================================================================================
;
ITIM_INT:
	IN	A,(ITIM_IO_CTL)		; READ STATUS
	AND	ITIM_ST_INTREQ		; ARE WE ASSERTING INT?
	RET	Z			; IF NOT, SIGNAL INT NOT HANDLED
;
	; PROCESS THE INTERRUPT.  THE ACK TAKES EFFECT BEFORE THE NEXT
	; INSTRUCTION, SO INT IS RELEASED WELL BEFORE THE RETURN AND EI.
	LD	A,ITIM_CMD_ACK
	OUT	(ITIM_IO_CMD),A		; RELEASE THE INTERRUPT REQUEST
	JP	HB_TIMINT		; CHAIN TO TIMER PROCESSING
;
;==================================================================================================
; DETECT THE TIMER BY WRITING DIFFERENT PATTERNS TO THE TWO INTERVAL BYTES
; AND READING THEM BACK.  AN EMPTY BUS CANNOT RETURN BOTH.  LEAVES THE
; INTERVAL AT ZERO (ITS RESET VALUE).  RETURNS ZERO (ZF SET) IF PRESENT.
;==================================================================================================
;
ITIM_DETECT:
	LD	A,$A5
	OUT	(ITIM_IO_INTLO),A	; WRITE PATTERN TO LOW BYTE
	CPL				; $5A
	OUT	(ITIM_IO_INTHI),A	; DIFFERENT PATTERN TO HIGH BYTE
	IN	A,(ITIM_IO_INTLO)	; READ LOW BYTE BACK
	CP	$A5			; SAME?
	JR	NZ,ITIM_DETECT1		; IF NOT, NOT PRESENT
	IN	A,(ITIM_IO_INTHI)	; READ HIGH BYTE BACK
	CP	$5A			; SAME?
	JR	NZ,ITIM_DETECT1		; IF NOT, NOT PRESENT
	XOR	A			; ZERO ACCUM
	OUT	(ITIM_IO_INTLO),A	; RESTORE INTERVAL TO ZERO
	OUT	(ITIM_IO_INTHI),A
	RET				; DONE, ZF SET (PRESENT)
ITIM_DETECT1:
	OR	$FF			; SIGNAL FAILURE
	RET				; DONE
;
; ITIM DRIVER DATA STORAGE
;
ITIM_EXIST	.DB	$FF		; SET TO ZERO IF EXISTS
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE TRAILER
;--------------------------------------------------------------------------------------------------
;
END_ITIM	.EQU	$
SIZ_ITIM	.EQU	END_ITIM - ORG_ITIM
;
	MEMECHO	"ITIM occupies "
	MEMECHO	SIZ_ITIM
	MEMECHO	" bytes.\n"
