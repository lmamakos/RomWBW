;
;==================================================================================================
;   ROMWBW DEBUG BUILD SETTINGS FOR MRZ80 FPGA
;==================================================================================================
;
; BRING-UP BUILD FOR THE MRZ80 PLATFORM.  MAXIMIZES DIAGNOSTIC OUTPUT
; TO HELP ISOLATE BOOT PROBLEMS (NO CONSOLE OUTPUT, HANGS, ETC).
;
; ROMWBW USES CASCADING CONFIGURATION FILES AS INDICATED BELOW:
;
; cfg_MASTER.asm			- MASTER: CONFIGURATION FILE DEFINES ALL POSSIBLE ROMWBW SETTINGS
; |
; +-> cfg_<platform>.asm		- PLATFORM: DEFAULT SETTINGS FOR SPECIFIC PLATFORM
;     |
;     +-> Config/<plt>_std.asm		- BUILD: SETTINGS FOR EACH OFFICIAL DIST BUILD
;         |
;         +-> Config/<plt>_<cust>.asm	- USER: CUSTOM USER BUILD SETTINGS
;
; OTHER THAN THE TOP MASTER FILE, EACH FILE MUST "#INCLUDE" ITS PARENT
; FILE (SEE #INCLUDE STATEMENT BELOW).
;
; *** WARNING: ASIDE FROM THE MASTER CONFIGURATION FILE, YOU MUST USE
; ".SET" TO OVERRIDE SETTINGS.  THE ASSEMBLER WILL ERROR IF YOU ATTEMPT
; TO USE ".EQU" BECAUSE IT WON'T LET YOU REDEFINE A SETTING WITH ".EQU".
;
#INCLUDE "cfg_MRZ80.asm"
;
; MAXIMUM HBIOS DIAGNOSTIC OUTPUT: DL_[NONE|CRITICAL|ERROR|WARNING|INFO|DETAIL|VERBOSE]
DIAGLVL		.SET	DL_VERBOSE	; HBIOS DISPLAYS ANYTHING IT KNOWS HOW TO
;
; MAXIMUM DRIVER TRACE OUTPUT
ANSITRACE	.SET	2		; ANSI DRIVER TRACE LEVEL (0=NO,1=ERRORS,2=ALL)
PPKTRACE	.SET	2		; PPK DRIVER TRACE LEVEL (0=NO,1=ERRORS,2=ALL)
KBDTRACE	.SET	2		; KBD DRIVER TRACE LEVEL (0=NO,1=ERRORS,2=ALL)
MDTRACE		.SET	2		; MD: TRACE LEVEL (0=NO,1=ERRORS,2=ALL)
;
; DISPLAY THE ASCII PLATFORM BANNER FIRST THING AT BOOT AS A CONSOLE
; CANARY (IF YOU SEE IT, CONSOLE OUTPUT IS WORKING)
BOOT_PRETTY	.SET	TRUE		; BOOT WITH PRETTY PLATFORM NAME
;
; WAIT A FEW SECONDS BEFORE BOOTING SO THE CONSOLE CAN CATCH UP
BOOT_TIMEOUT	.SET	5		; AUTO BOOT TIMEOUT IN SECONDS, -1 TO DISABLE, 0 FOR IMMEDIATE
