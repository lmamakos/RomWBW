;
;=============================================================================
;   MRZ80 HPS BLOCK DEVICE DISK DRIVER (MISTER FPGA Z80 SYSTEM)
;=============================================================================
;
; DISK DEVICE DRIVER FOR THE BLOCK STORAGE INTERFACE ON THE MRZ80 MISTER
; FPGA SYSTEM.  THE HDL IMPLEMENTS A SIMPLE REGISTER INTERFACE WITH A
; HIGH LEVEL ABSTRACTION: THE FPGA ASKS THE MISTER LINUX HOST (HPS) TO
; MOVE 512 BYTE BLOCKS BETWEEN AN IMAGE FILE AND THE DEVICE.  THE IMAGE
; FILE IS SELECTED AND MOUNTED IN THE MISTER OSD (ON SCREEN DISPLAY).
;
; THE FPGA ALSO HAS A SECOND DEVICE WITH THE SAME REGISTER LAYOUT THAT
; TALKS SPI TO A PHYSICAL SD CARD (BASE 0x88).  IT HAS NO SIZE REGISTERS
; AND REQUIRES A STATUS CHECK PER BYTE.  IT IS NOT FUNCTIONAL AT THIS TIME
; AND IS NOT SUPPORTED BY THIS DRIVER YET.  ONLY THE HPS BLOCK DEVICE
; (BASE 0x90) IS IMPLEMENTED.
;
; REGISTER MAP (OFFSETS FROM THE BASE PORT, 0x90 FOR THE HPS DEVICE)
;
;  OFFSET | READ   | WRITE   | NOTES
;  -------|--------|---------|---------------------------------------------
;  +0     | DATA   | DATA    | SEQUENTIAL BYTE STREAM OF THE CURRENT BLOCK
;  +1     | STATUS | CONTROL | CONTROL: 0x00 = READ BLOCK, 0x01 = WRITE BLOCK
;  +2     | -      | LBA0    | BLOCK NUMBER BITS 7:0
;  +3     | -      | LBA1    | BLOCK NUMBER BITS 15:8
;  +4     | -      | LBA2    | BLOCK NUMBER BITS 23:16 (24 BITS = 8 GB)
;  +5     | SIZE0  | -       | IMAGE SIZE IN 512 BYTE BLOCKS, BITS 7:0
;  +6     | SIZE1  | -       | BITS 15:8
;  +7     | SIZE2  | -       | BITS 23:16 (SATURATES AT 0xFFFFFF)
;
; STATUS BITS
;
;  BIT 7   WRITE BYTE CAN BE ACCEPTED (IDLE, OR FILLING THE WRITE BUFFER)
;  BIT 6   READ BYTE AVAILABLE
;  BIT 5   BLOCK BUSY (COMMAND IN PROGRESS, WAITING FOR THE HPS)
;  BIT 4   NO IMAGE MOUNTED
;  BIT 3   IMAGE IS READ-ONLY
;  BIT 2   LAST COMMAND REJECTED (NO IMAGE, LBA >= SIZE, WRITE TO READ-ONLY
;          IMAGE).  CLEARED BY THE NEXT ACCEPTED COMMAND.
;  BIT 1:0 ALWAYS 0
;
; TYPICAL STATUS VALUES: 0x90 NO IMAGE, 0x80 IDLE (0x88 IF READ-ONLY),
; 0x20 COMMAND ACCEPTED AND WAITING FOR HPS, 0xE0 READ DATA READY,
; 0xA0 READY FOR WRITE DATA, 0x84/0x8C IDLE WITH THE REJECTED FLAG SET.
;
; PROGRAMMING SEQUENCE
;
;   READ:  WAIT STATUS & 0xF0 = 0x80, WRITE LBA0-2, WRITE CONTROL 0x00,
;          WAIT STATUS & 0xE0 = 0xE0 (OR REJECT, BIT 2), THEN 512 BYTES
;          FROM DATA.  DEVICE RETURNS TO IDLE AFTER THE 512TH BYTE.
;   WRITE: SAME, CONTROL 0x01, WAIT STATUS & 0xE0 = 0xA0, THEN 512 BYTES
;          TO DATA.  THE DEVICE THEN WRITES THE BLOCK AND RETURNS TO IDLE
;          (STATUS 0x20 UNTIL THE HPS HAS TAKEN THE DATA).
;
; THE HPS DEVICE HOLDS THE READ/WRITE READY BITS FOR THE WHOLE BLOCK, SO
; AFTER THE FIRST STATUS CHECK THE 512 BYTES ARE MOVED WITH INIR/OTIR.
;
; THE HPS ROUND TRIP GOES THROUGH LINUX AND CAN TAKE A WHILE, SO TIMEOUTS
; ARE GENEROUS (SEVERAL SECONDS).
;
; Starting point for this driver was the ESPSD.ASM driver for the 
; S100Computers system.
;

MRZ80SD_IO_DATA		.EQU	0	; DATA PORT OFFSET
MRZ80SD_IO_STATUS	.EQU	1	; STATUS (R) / CONTROL (W) PORT OFFSET
MRZ80SD_IO_LBA0		.EQU	2	; LBA BITS 7:0 (W), LBA1 = +3, LBA2 = +4
MRZ80SD_IO_SIZE0	.EQU	5	; SIZE BITS 7:0 (R), SIZE1 = +6, SIZE2 = +7
;
MRZ80SD_CTL_READ	.EQU	$00	; CONTROL: READ BLOCK
MRZ80SD_CTL_WRITE	.EQU	$01	; CONTROL: WRITE BLOCK
;
MRZ80SD_TMO		.EQU	100 * CPUMHZ	; WAIT FOR IDLE: OUTER LOOPS OF 256 POLLS
MRZ80SD_TMOCMD		.EQU	16	; WAIT FOR CMD: OUTER LOOPS OF 65536 POLLS
;
; DRIVER STATUS CODES (INTERNAL, KEPT IN CFG ENTRY)
;
MRZ80SD_STOK		.EQU	0
MRZ80SD_STNOMEDIA	.EQU	-1
MRZ80SD_STIOERR		.EQU	-2
MRZ80SD_STTO		.EQU	-3
MRZ80SD_STNOTRDY	.EQU	-4
;
; DEVICE TYPES (FOR MRZ80SD_TYPE IN THE CFG ENTRY)
;
MRZ80SD_TYPE_HPS	.EQU	0	; HPS IMAGE BLOCK DEVICE (0x90)
MRZ80SD_TYPE_SPI	.EQU	1	; SPI SD CARD (0x88), NOT YET SUPPORTED
;
; PER DEVICE DATA OFFSETS IN CFG BLOCK
;
MRZ80SD_DEV		.EQU	0	; OFFSET OF DEVICE NUMBER (BYTE)
MRZ80SD_TYPE		.EQU	1	; DEVICE TYPE (BYTE)
MRZ80SD_IOBASE		.EQU	2	; IO BASE ADDRESS (BYTE)
MRZ80SD_STAT		.EQU	3	; LAST STATUS (BYTE)
MRZ80SD_MEDCAP		.EQU	4	; MEDIA CAPACITY IN BLOCKS (DWORD)
MRZ80SD_LBA		.EQU	8	; OFFSET OF LBA (DWORD)
;
;--------------------------------------------------------------------------------------------------
;   HBIOS MODULE HEADER
;--------------------------------------------------------------------------------------------------
;
ORG_MRZ80SD	.EQU	$
;
	.DW	SIZ_MRZ80SD		; MODULE SIZE
	.DW	MRZ80SD_INITPHASE	; ADR OF INIT PHASE HANDLER
;
MRZ80SD_INITPHASE:
	; INIT PHASE HANDLER, A=PHASE
	CP	HB_PHASE_INIT		; INIT PHASE?
	JP	Z,MRZ80SD_INIT		; DO INIT
	RET				; DONE
;
MRZ80SD_CFGSIZ		.EQU	12	; SIZE OF CFG TBL ENTRIES
;
MRZ80SD_CFGTBL:
;
#IF (MRZ80SDCNT >= 1)
;
MRZ80SD_DEV0:	; DEVICE 0, HPS BLOCK DEVICE
	.DB	$FE			; DRIVER DEVICE NUMBER (FILLED DYNAMICALLY)
	.DB	MRZ80SD_TYPE_HPS	; DEVICE TYPE
	.DB	MRZ80SD0BASE		; IO BASE ADDRESS
	.DB	MRZ80SD_STNOTRDY	; DEVICE STATUS
	.DW	$0000,$0000		; DEVICE CAPACITY (BLOCKS)
	.DW	0,0			; CURRENT LBA
;
	DEVECHO	"MRZ80SD: IO="
	DEVECHO	MRZ80SD0BASE
	DEVECHO	", HPS BLOCK DEVICE"
	DEVECHO	"\n"
;
#ENDIF
;
#IF (MRZ80SDCNT >= 2)
	.ECHO	"*** MRZ80SD: SPI SD CARD (MRZ80SDCNT >= 2) NOT YET SUPPORTED ***\n"
#ENDIF
;
#IF ($ - MRZ80SD_CFGTBL) != (MRZ80SDCNT * MRZ80SD_CFGSIZ)
	.ECHO	"*** INVALID MRZ80SD CONFIG TABLE ***\n"
#ENDIF
;
	.DB	$FF			; END OF TABLE MARKER
;
;=============================================================================
; INITIALIZATION ENTRY POINT
;=============================================================================
;
MRZ80SD_INIT:
;
	XOR	A			;
	LD	(MRZ80SD_DEVNUM),A	; INIT DEV UNIT NUM FOR DYNAMIC ASSIGNMENT
	LD	IY,MRZ80SD_CFGTBL	; POINT TO START OF CONFIG TABLE
;
MRZ80SD_INIT1:
	LD	A,(IY)			; LOAD FIRST BYTE TO CHECK FOR END
	CP	$FF			; CHECK FOR END OF TABLE VALUE
	JR	NZ,MRZ80SD_INIT2	; IF NOT END OF TABLE, CONTINUE
	XOR	A			; SIGNAL SUCCESS
	RET				; AND RETURN
;
MRZ80SD_INIT2:
	CALL	NEWLINE			; FORMATTING
	PRTS("MRZ80SD:$")		; TAG
;
	PRTS(" IO=0x$")			; LABEL FOR IO ADDRESS
	LD	A,(IY+MRZ80SD_IOBASE)	; GET IO BASE ADDRES
	CALL	PRTHEXBYTE		; DISPLAY IT
;
	CALL	MRZ80SD_DETECT		; PROBE FOR INTERFACE
	JR	Z,MRZ80SD_INIT3		; GOT IT, MOVE ON TO INIT UNIT
	PRTS(" NOT PRESENT$")		; SHOW NOT PRESENT
	JR	MRZ80SD_INIT4		; SKIP CFG ENTRY
;
MRZ80SD_INIT3:
	CALL	MRZ80SD_INIT5		; REGISTER & INIT DEVICE
;
MRZ80SD_INIT4:
	LD	DE,MRZ80SD_CFGSIZ	; SIZE OF CFG TABLE ENTRY
	ADD	IY,DE			; BUMP POINTER
	JP	MRZ80SD_INIT1		; AND LOOP
;
MRZ80SD_INIT5:
	; UPDATE DRIVER RELATIVE UNIT NUMBER IN CONFIG TABLE
	LD	A,(MRZ80SD_DEVNUM)	; GET NEXT UNIT NUM TO ASSIGN
	LD	(IY+MRZ80SD_DEV),A	; UPDATE IT
	INC	A			; BUMP TO NEXT UNIT NUM TO ASSIGN
	LD	(MRZ80SD_DEVNUM),A	; SAVE IT
;
	; ADD UNIT TO GLOBAL DISK UNIT TABLE
	LD	BC,MRZ80SD_FNTBL	; BC := FUNC TABLE ADR
	PUSH	IY			; CFG ENTRY POINTER
	POP	DE			; COPY TO DE
	CALL	DIO_ADDENT		; ADD ENTRY TO GLOBAL DISK DEV TABLE
;
	CALL	MRZ80SD_INITDEV		; INITIALIZE DEVICE
#IF (MRZ80SDTRACE < 2)
	JP	NZ,MRZ80SD_PRTSTAT	; SHOW WHY NOT READY
#ELSE
	RET	NZ			; (ALREADY SHOWN BY TRACE)
#ENDIF
;
	CALL	MRZ80SD_PRTPREFIX	; TAG FOR ACTIVE DEVICE
;
	; PRINT STORAGE CAPACITY (BLOCK COUNT)
	PRTS(" BLOCKS=0x$")		; PRINT FIELD LABEL
	LD	A,MRZ80SD_MEDCAP	; OFFSET TO CAPACITY FIELD
	CALL	LDHLIYA			; HL := IY + A, REG A TRASHED
	CALL	LD32			; GET THE CAPACITY VALUE
	CALL	PRTHEX32		; PRINT HEX VALUE
;
	; PRINT STORAGE SIZE IN MB
	PRTS(" SIZE=$")			; PRINT FIELD LABEL
	LD	B,11			; 11 BIT SHIFT TO CONVERT BLOCKS --> MB
	CALL	SRL32			; RIGHT SHIFT
	CALL	PRTDEC32		; PRINT DWORD IN DECIMAL
	PRTS("MB$")			; PRINT SUFFIX
;
	; NOTE IF THE IMAGE IS READ-ONLY
	LD	C,(IY+MRZ80SD_IOBASE)	; BASE PORT
	INC	C			; STATUS PORT
	IN	A,(C)			; GET STATUS
	BIT	3,A			; READ-ONLY?
	JR	Z,MRZ80SD_INIT6		; IF NOT, SKIP
	PRTS(" RO$")			; SHOW READ-ONLY
;
MRZ80SD_INIT6:
	XOR	A			; SUCCESS
	RET
;
;=============================================================================
; DRIVER FUNCTION TABLE
;=============================================================================
;
MRZ80SD_FNTBL:
	.DW	MRZ80SD_STATUS
	.DW	MRZ80SD_RESET
	.DW	MRZ80SD_SEEK
	.DW	MRZ80SD_READ
	.DW	MRZ80SD_WRITE
	.DW	MRZ80SD_VERIFY
	.DW	MRZ80SD_FORMAT
	.DW	MRZ80SD_DEVICE
	.DW	MRZ80SD_MEDIA
	.DW	MRZ80SD_DEFMED
	.DW	MRZ80SD_CAP
	.DW	MRZ80SD_GEOM
#IF (($ - MRZ80SD_FNTBL) != (DIO_FNCNT * 2))
	.ECHO	"*** INVALID MRZ80SD FUNCTION TABLE ***\n"
#ENDIF
;
MRZ80SD_VERIFY:
MRZ80SD_FORMAT:
MRZ80SD_DEFMED:
	SYSCHKERR(ERR_NOTIMPL)		; NOT IMPLEMENTED
	RET
;
; READ ONE BLOCK.  HB_DSKREAD CALLS THE CODE FOLLOWING IT ONCE PER
; BLOCK WITH HL = BUFFER ADDRESS.
;
MRZ80SD_READ:
	CALL	HB_DSKREAD		; HOOK HBIOS DISK READ SUPERVISOR
	LD	E,MRZ80SD_CTL_READ	; SETUP FOR BLOCK READ CMD
	JP	MRZ80SD_IO		; CONTINUE TO GENERIC IO ROUTINE
;
; WRITE ONE BLOCK.  SEE ABOVE.
;
MRZ80SD_WRITE:
	CALL	HB_DSKWRITE		; HOOK HBIOS DISK WRITE SUPERVISOR
	LD	E,MRZ80SD_CTL_WRITE	; SETUP FOR BLOCK WRITE CMD
	JP	MRZ80SD_IO		; CONTINUE TO GENERIC IO ROUTINE
;
; RETURN UNIT STATUS
;
MRZ80SD_STATUS:
	LD	A,(IY+MRZ80SD_STAT)	; GET STATUS OF SELECTED DEVICE
	OR	A			; SET FLAGS
	RET				; AND RETURN
;
; RESET (REINITIALIZE) THE UNIT
;
MRZ80SD_RESET:
	CALL	MRZ80SD_INITDEV		; REINITIALIZE UNIT
	OR	A			; SET RESULT FLAGS
	RET
;
; REPORT DEVICE INFORMATION
;
MRZ80SD_DEVICE:
	LD	D,DIODEV_MRZ80SD	; D := DEVICE TYPE
	LD	E,(IY+MRZ80SD_DEV)	; E := PHYSICAL DEVICE NUMBER
	LD	C,%01110000		; C := ATTRIBUTES: REMOVABLE, HIGH CAPACITY,
					; LBA CAPABLE, MEDIA TYPE 0 (HARD DISK)
	LD	H,0			; H := MODE
	LD	L,(IY+MRZ80SD_IOBASE)	; L := BASE I/O ADDRESS
	XOR	A			; SIGNAL SUCCESS
	RET
;
; REPORT MEDIA.  IF E <> 0, RE-DISCOVER THE MEDIA (PICKS UP AN IMAGE
; MOUNTED OR CHANGED IN THE OSD SINCE INIT).
;
MRZ80SD_MEDIA:
	LD	A,E			; GET FLAGS
	OR	A			; SET FLAGS
	JR	Z,MRZ80SD_MEDIA1	; JUST REPORT CURRENT STATUS AND MEDIA
;
	CALL	MRZ80SD_INITDEV		; REINITIALIZE DEVICE
;
MRZ80SD_MEDIA1:
	LD	A,(IY+MRZ80SD_STAT)	; GET STATUS
	OR	A			; SET FLAGS
	LD	D,0			; NO MEDIA CHANGE DETECTED
	LD	E,MID_HD		; ASSUME WE ARE OK
	RET	Z			; RETURN IF GOOD INIT
	LD	E,MID_NONE		; SIGNAL NO MEDIA
	LD	A,ERR_NOMEDIA		; NO MEDIA ERROR
	OR	A			; SET FLAGS
	RET				; AND RETURN
;
; SEEK: SAVE THE LBA FOR THE NEXT READ/WRITE
;
MRZ80SD_SEEK:
	BIT	7,D			; CHECK FOR LBA FLAG
	CALL	Z,HB_CHS2LBA		; CLEAR MEANS CHS, CONVERT TO LBA
	RES	7,D			; CLEAR FLAG REGARDLESS (DOES NO HARM IF ALREADY LBA)
	LD	(IY+MRZ80SD_LBA+0),L	; SAVE NEW LBA
	LD	(IY+MRZ80SD_LBA+1),H	; ...
	LD	(IY+MRZ80SD_LBA+2),E	; ...
	LD	(IY+MRZ80SD_LBA+3),D	; ...
	XOR	A			; SIGNAL SUCCESS
	RET				; AND RETURN
;
; REPORT CAPACITY IN BLOCKS (DE:HL) AND BLOCK SIZE (BC)
;
MRZ80SD_CAP:
	LD	A,(IY+MRZ80SD_STAT)	; GET STATUS
	PUSH	AF			; SAVE IT
	LD	A,MRZ80SD_MEDCAP	; OFFSET TO CAPACITY FIELD
	CALL	LDHLIYA			; HL := IY + A, REG A TRASHED
	CALL	LD32			; GET THE CURRENT CAPACITY INTO DE:HL
	LD	BC,512			; 512 BYTES PER BLOCK
	POP	AF			; RECOVER STATUS
	OR	A			; SET FLAGS
	RET
;
; REPORT GEOMETRY
;
MRZ80SD_GEOM:
	; FOR LBA, WE SIMULATE CHS ACCESS USING 16 HEADS AND 16 SECTORS
	; RETURN HS:CC -> DE:HL, SET HIGH BIT OF D TO INDICATE LBA CAPABLE
	CALL	MRZ80SD_CAP		; GET TOTAL BLOCKS IN DE:HL, BLOCK SIZE TO BC
	LD	L,H			; DIVIDE BY 256 FOR # TRACKS
	LD	H,E			; ... HIGH BYTE DISCARDED, RESULT IN HL
	LD	D,16 | $80		; HEADS / CYL = 16, SET LBA CAPABILITY BIT
	LD	E,16			; SECTORS / TRACK = 16
	RET				; DONE, A STILL HAS MRZ80SD_CAP STATUS
;
;=============================================================================
; FUNCTION SUPPORT ROUTINES
;=============================================================================
;
; PROBE FOR THE INTERFACE.  ZF SET ON RETURN INDICATES HARDWARE FOUND.
;
; UNCLAIMED I/O PORTS READ AS $FF ON THIS SYSTEM.  A REAL STATUS VALUE
; HAS BITS 1:0 CLEAR AND AT LEAST ONE OF BITS 7, 5, 4 SET.
;
MRZ80SD_DETECT:
	LD	C,(IY+MRZ80SD_IOBASE)	; BASE PORT
	INC	C			; STATUS PORT
	IN	A,(C)			; GET STATUS
	LD	B,A			; SAVE IT
	AND	%00000011		; BITS 1:0 MUST BE ZERO
	JR	NZ,MRZ80SD_DETECT1	; IF NOT, NOT PRESENT
	LD	A,B			; RECOVER STATUS
	AND	%10110000		; ANY OF 7, 5, 4 MUST BE SET
	JR	Z,MRZ80SD_DETECT1	; IF NOT, NOT PRESENT
	XOR	A			; SIGNAL FOUND (ZF SET)
	RET
MRZ80SD_DETECT1:
	LD	A,$FF			; SIGNAL NOT FOUND
	OR	A			; SET NZ
	RET
;
; INITIALIZE DEVICE: WAIT FOR IDLE, THEN READ THE IMAGE SIZE.  AN
; UNMOUNTED IMAGE (OR A ZERO SIZE) IS REPORTED AS NO MEDIA.
; ON RETURN A=0, ZF SET ON SUCCESS, OTHERWISE A=STATUS CODE, NZ.
;
MRZ80SD_INITDEV:
	; CLEAR CAPACITY (STAYS ZERO IF NO MEDIA)
	XOR	A			; ZERO
	LD	(IY+MRZ80SD_MEDCAP+0),A	; ...
	LD	(IY+MRZ80SD_MEDCAP+1),A	; ...
	LD	(IY+MRZ80SD_MEDCAP+2),A	; ...
	LD	(IY+MRZ80SD_MEDCAP+3),A	; ...
;
	CALL	MRZ80SD_WAITIDLE	; WAIT FOR DEVICE TO BE IDLE
	JP	NZ,MRZ80SD_ERR		; NO MEDIA OR TIMEOUT, RECORD AND EXIT
;
	; READ THE IMAGE SIZE (BLOCKS), 24 BITS
	LD	A,(IY+MRZ80SD_IOBASE)	; BASE PORT
	ADD	A,MRZ80SD_IO_SIZE0	; SIZE0 PORT
	LD	C,A			; PORT TO C
	IN	A,(C)			; SIZE0
	LD	(IY+MRZ80SD_MEDCAP+0),A	; SAVE
	INC	C			; SIZE1 PORT
	IN	A,(C)			; SIZE1
	LD	(IY+MRZ80SD_MEDCAP+1),A	; SAVE
	INC	C			; SIZE2 PORT
	IN	A,(C)			; SIZE2
	LD	(IY+MRZ80SD_MEDCAP+2),A	; SAVE
;
	; A SIZE OF ZERO MEANS NO MEDIA
	OR	(IY+MRZ80SD_MEDCAP+1)	; COMBINE
	OR	(IY+MRZ80SD_MEDCAP+0)	; ... ALL THREE BYTES
	LD	A,MRZ80SD_STNOMEDIA	; ASSUME NO MEDIA (FLAGS UNCHANGED)
	JP	Z,MRZ80SD_ERR		; IF ZERO, RECORD AND EXIT
;
	; RESET STATUS
	XOR	A			; STATUS OK
	LD	(IY+MRZ80SD_STAT),A	; SAVE IT
	RET				; DONE, ZF SET
;
; WAIT FOR THE DEVICE TO BE IDLE (STATUS & $F0 = $80).
; ON RETURN: A=0, ZF SET IF IDLE
;            A=MRZ80SD_STNOMEDIA, NZ IF NO IMAGE IS MOUNTED
;            A=MRZ80SD_STTO, NZ IF TIMEOUT
; PRESERVES HL.  DESTROYS BC, DE.
;
MRZ80SD_WAITIDLE:
	LD	C,(IY+MRZ80SD_IOBASE)	; BASE PORT
	INC	C			; STATUS PORT
	LD	DE,MRZ80SD_TMO		; OUTER LOOP COUNTER
;
MRZ80SD_WAITIDLE1:	; OUTER LOOP
	LD	B,0			; INNER LOOP COUNTER
;
MRZ80SD_WAITIDLE2:	; INNER LOOP
	IN	A,(C)			; GET STATUS
	BIT	4,A			; NO IMAGE MOUNTED?
	JR	NZ,MRZ80SD_WAITIDLE4	; IF SO, NO MEDIA
	AND	$F0			; ISOLATE STATE BITS
	CP	$80			; IDLE?
	JR	Z,MRZ80SD_WAITIDLE3	; IF SO, DONE
	DJNZ	MRZ80SD_WAITIDLE2	; LOOP SOME MORE
;
	DEC	DE			; DEC OUTER LOOP COUNTER
	LD	A,D			; TEST COUNTER
	OR	E			; ... FOR ZERO
	JR	NZ,MRZ80SD_WAITIDLE1	; IF NOT ZERO, LOOP MORE
;
	LD	A,MRZ80SD_STTO		; TIMEOUT
	OR	A			; SET NZ
	RET
;
MRZ80SD_WAITIDLE3:
	XOR	A			; SUCCESS
	RET
;
MRZ80SD_WAITIDLE4:
	LD	A,MRZ80SD_STNOMEDIA	; NO MEDIA
	OR	A			; SET NZ
	RET
;
; COMMON BLOCK I/O
;
; ON ENTRY: E = CONTROL VALUE (MRZ80SD_CTL_READ OR _WRITE), HL = BUFFER
;           (IY+MRZ80SD_LBA) = BLOCK NUMBER
; ON EXIT:  A = HBIOS STATUS, ZF SET FOR SUCCESS, HL = BUFFER ADR + 512
;
MRZ80SD_IO:
;
#IF (MRZ80SDTRACE == 1)
	PUSH	HL
	LD	HL,MRZ80SD_PRTERR	; SET UP MRZ80SD_PRTERR
	EX	(SP),HL			; ... TO FILTER ALL EXITS
#ENDIF
;
	LD	A,E			; COMMAND TO ACCUM
	LD	(MRZ80SD_CMDVAL),A	; SAVE THE COMMAND
	LD	(MRZ80SD_DSKBUF),HL	; SAVE DISK BUFFER ADDRESS
;
	; IF DEVICE IS IN ERROR STATE, TRY TO RECOVER
	CALL	MRZ80SD_CHKERR		; CHECK FOR ERR STATUS AND RESET IF SO
	JP	NZ,MRZ80SD_IOSTAT	; STILL IN ERROR, A = STATUS CODE
;
	; WAIT FOR DEVICE IDLE
	CALL	MRZ80SD_WAITIDLE	; WAIT FOR IDLE
	JP	NZ,MRZ80SD_IOSTAT	; NO MEDIA OR TIMEOUT
;
	; A WRITE TO A READ-ONLY IMAGE IS REJECTED BY THE DEVICE, BUT
	; REPORT IT PROPERLY
	LD	A,(MRZ80SD_CMDVAL)	; GET COMMAND
	OR	A			; READ?
	JR	Z,MRZ80SD_IO1		; IF SO, SKIP
	LD	C,(IY+MRZ80SD_IOBASE)	; BASE PORT
	INC	C			; STATUS PORT
	IN	A,(C)			; GET STATUS
	BIT	3,A			; READ-ONLY IMAGE?
	LD	A,ERR_READONLY		; ASSUME SO (FLAGS UNCHANGED)
	JP	NZ,MRZ80SD_IOX		; IF SO, FAIL
;
MRZ80SD_IO1:
	; ONLY 24 BIT BLOCK NUMBERS ARE SUPPORTED
	LD	A,(IY+MRZ80SD_LBA+3)	; HIGH BYTE OF LBA
	OR	A			; ZERO?
	LD	A,ERR_RANGE		; ASSUME NOT (FLAGS UNCHANGED)
	JP	NZ,MRZ80SD_IOX		; IF NOT ZERO, FAIL
;
	; SHOW ACTIVITY
	LD	A,MRZ80SD_LBA		; OFFSET OF LBA VALUE
	CALL	LDHLIYA			; HL := IY + A, REG A TRASHED
	CALL	HB_DSKACT		; SHOW ACTIVITY
;
	; SEND LBA TO DEVICE
	LD	C,(IY+MRZ80SD_IOBASE)	; BASE PORT
	INC	C			; STATUS/CONTROL PORT
	INC	C			; LBA0 PORT
	LD	A,(IY+MRZ80SD_LBA+0)	; LBA BITS 7:0
	OUT	(C),A			; SEND
	INC	C			; LBA1 PORT
	LD	A,(IY+MRZ80SD_LBA+1)	; LBA BITS 15:8
	OUT	(C),A			; SEND
	INC	C			; LBA2 PORT
	LD	A,(IY+MRZ80SD_LBA+2)	; LBA BITS 23:16
	OUT	(C),A			; SEND
;
	; ISSUE THE COMMAND
	LD	C,(IY+MRZ80SD_IOBASE)	; BASE PORT
	INC	C			; CONTROL / STATUS PORT
	LD	A,(MRZ80SD_CMDVAL)	; GET COMMAND
	OUT	(C),A			; ISSUE IT
;
	; WAIT FOR DATA READY: STATUS & $E0 = $E0 FOR READ, $A0 FOR WRITE.
	; ALSO WATCH FOR COMMAND REJECTED OR IMAGE UNMOUNTED.
	LD	D,$E0			; READ READY VALUE
	OR	A			; READ COMMAND?
	JR	Z,MRZ80SD_IO2		; IF SO, SKIP
	LD	D,$A0			; WRITE READY VALUE
;
MRZ80SD_IO2:
	LD	E,MRZ80SD_TMOCMD	; OUTER LOOP COUNTER
;
MRZ80SD_IO3:	; OUTER LOOP
	LD	HL,0			; INNER LOOP COUNTER
;
MRZ80SD_IO4:	; INNER LOOP
	IN	A,(C)			; GET STATUS
	LD	B,A			; SAVE IT
	AND	$E0			; ISOLATE STATE BITS
	CP	D			; DATA READY?
	JR	Z,MRZ80SD_IO5		; IF SO, TRANSFER DATA
	LD	A,B			; RECOVER STATUS
	AND	$F4			; IDLE WITH REJECTED FLAG?
	CP	$84			; ...
	JR	Z,MRZ80SD_IOREJ		; IF SO, COMMAND REJECTED
	BIT	4,B			; IMAGE UNMOUNTED?
	JR	NZ,MRZ80SD_IONOMED	; IF SO, NO MEDIA
	DEC	HL			; DEC INNER COUNTER
	LD	A,H			; TEST COUNTER
	OR	L			; ... FOR ZERO
	JR	NZ,MRZ80SD_IO4		; LOOP MORE
	DEC	E			; DEC OUTER COUNTER
	JR	NZ,MRZ80SD_IO3		; LOOP MORE
;
	LD	A,MRZ80SD_STTO		; TIMEOUT
	JP	MRZ80SD_IOSTAT		; RECORD AND EXIT
;
MRZ80SD_IO5:
	; TRANSFER 512 BYTES.  THE DEVICE HOLDS THE READY BITS FOR THE
	; WHOLE BLOCK, SO NO PER-BYTE STATUS CHECK IS NEEDED.
	LD	HL,(MRZ80SD_DSKBUF)	; RECOVER THE DISK BUFFER ADR
	LD	C,(IY+MRZ80SD_IOBASE)	; DATA PORT IS THE BASE PORT
	LD	B,0			; 256 BYTES PER BLOCK
	LD	A,(MRZ80SD_CMDVAL)	; GET COMMAND
	OR	A			; READ?
	JR	NZ,MRZ80SD_IO5W		; IF NOT, DO WRITE
	INIR				; READ FIRST 256 BYTES
	INIR				; READ SECOND 256 BYTES
	JR	MRZ80SD_IO6		; CONTINUE
MRZ80SD_IO5W:
	OTIR				; WRITE FIRST 256 BYTES
	OTIR				; WRITE SECOND 256 BYTES
;
MRZ80SD_IO6:
	LD	(MRZ80SD_DSKBUF),HL	; SAVE UPDATED BUFFER ADDRESS
;
	; WAIT FOR COMPLETION.  FOR A WRITE THIS COVERS THE HPS ACTUALLY
	; TAKING THE BLOCK.
	CALL	MRZ80SD_WAITIDLE	; WAIT FOR IDLE
	JP	NZ,MRZ80SD_IOSTAT	; NO MEDIA OR TIMEOUT
;
	; MAKE SURE THE ERROR FLAG IS CLEAR
	LD	C,(IY+MRZ80SD_IOBASE)	; BASE PORT
	INC	C			; STATUS PORT
	IN	A,(C)			; GET STATUS
	BIT	2,A			; REJECTED?
	JR	NZ,MRZ80SD_IOREJ	; IF SO, FAIL
;
	; INCREMENT LBA
	LD	A,MRZ80SD_LBA		; LBA OFFSET
	CALL	LDHLIYA			; HL := IY + A, REG A TRASHED
	CALL	INC32HL			; INCREMENT THE VALUE
;
	XOR	A			; SIGNAL SUCCESS
	LD	HL,(MRZ80SD_DSKBUF)	; UPDATED DMA ADDRESS TO HL
	RET				; DONE
;
MRZ80SD_IOREJ:
	; DEVICE REJECTED THE COMMAND: NO IMAGE, LBA >= SIZE, OR
	; WRITE TO READ-ONLY IMAGE (WHICH WE CHECKED ALREADY)
	LD	A,ERR_RANGE		; REPORT AS RANGE ERROR
	JR	MRZ80SD_IOX		; DONE
;
MRZ80SD_IONOMED:
	LD	A,MRZ80SD_STNOMEDIA	; NO MEDIA
	; FALL THRU TO MRZ80SD_IOSTAT
;
; RECORD DRIVER STATUS CODE IN A AND CONVERT IT TO AN HBIOS ERROR
;
MRZ80SD_IOSTAT:
	CALL	MRZ80SD_ERR		; RECORD STATUS (PRESERVES A)
	CP	MRZ80SD_STNOMEDIA	; NO MEDIA?
	JR	Z,MRZ80SD_IOSTAT1	; HANDLE IT
	CP	MRZ80SD_STTO		; TIMEOUT?
	JR	Z,MRZ80SD_IOSTAT2	; HANDLE IT
	CP	MRZ80SD_STNOTRDY	; NOT READY?
	JR	Z,MRZ80SD_IOSTAT3	; HANDLE IT
	LD	A,ERR_IO		; ANYTHING ELSE IS AN I/O ERROR
	JR	MRZ80SD_IOX		; DONE
MRZ80SD_IOSTAT1:
	LD	A,ERR_NOMEDIA		; NO MEDIA
	JR	MRZ80SD_IOX		; DONE
MRZ80SD_IOSTAT2:
	LD	A,ERR_TIMEOUT		; TIMEOUT
	JR	MRZ80SD_IOX		; DONE
MRZ80SD_IOSTAT3:
	LD	A,ERR_NOTRDY		; NOT READY
	; FALL THRU TO MRZ80SD_IOX
;
; COMMON ERROR EXIT, A = HBIOS ERROR CODE (NON-ZERO)
;
MRZ80SD_IOX:
	LD	HL,(MRZ80SD_DSKBUF)	; CURRENT DMA TO HL
	OR	A			; SET FLAGS
	RET				; AND DONE
;
; CHECK CURRENT DEVICE FOR ERROR STATUS AND ATTEMPT TO RECOVER
; VIA RESET IF DEVICE IS IN ERROR.  THIS ALSO PICKS UP AN IMAGE THAT
; WAS MOUNTED AFTER BOOT.  ZF SET ON RETURN IF DEVICE IS OK.
;
MRZ80SD_CHKERR:
	LD	A,(IY+MRZ80SD_STAT)	; GET STATUS
	OR	A			; SET FLAGS
	CALL	NZ,MRZ80SD_RESET	; IF ERROR STATUS, RESET DEVICE
	RET
;
;=============================================================================
; ERROR HANDLING AND DIAGNOSTICS
;=============================================================================
;
; RECORD STATUS CODE IN A IN THE CFG ENTRY.  A IS PRESERVED, FLAGS SET.
;
MRZ80SD_ERR:
	LD	(IY+MRZ80SD_STAT),A	; SAVE NEW STATUS
;
#IF (MRZ80SDTRACE >= 2)
	CALL	MRZ80SD_PRTSTAT
#ENDIF
	OR	A			; SET FLAGS
	RET
;
; EXIT FILTER FOR TRACE LEVEL 1: SHOW THE DEVICE STATUS ONLY WHEN THE
; DEVICE HAS A RECORDED ERROR
;
MRZ80SD_PRTERR:
	RET	Z			; DONE IF NO ERRORS
	PUSH	AF			; SAVE RESULT
	LD	A,(IY+MRZ80SD_STAT)	; GET DEVICE STATUS
	OR	A			; ANY RECORDED ERROR?
	JR	Z,MRZ80SD_PRTERR1	; IF NOT, DONE
	POP	AF			; RECOVER RESULT
	; FALL THRU TO MRZ80SD_PRTSTAT
;
; PRINT FULL DEVICE STATUS LINE
;
MRZ80SD_PRTSTAT:
	PUSH	AF
	PUSH	DE
	PUSH	HL
	CALL	MRZ80SD_PRTPREFIX	; PRINT UNIT PREFIX
	CALL	PC_SPACE		; FORMATTING
	CALL	MRZ80SD_PRTSTATSTR
	POP	HL
	POP	DE
	POP	AF
	RET
;
MRZ80SD_PRTERR1:
	POP	AF			; RECOVER RESULT (FLAGS INTACT)
	RET
;
; PRINT STATUS STRING
;
MRZ80SD_PRTSTATSTR:
	PUSH	AF
	PUSH	DE
	LD	A,(IY+MRZ80SD_STAT)
	OR	A
	LD	DE,MRZ80SD_STR_STOK
	JR	Z,MRZ80SD_PRTSTATSTR1
	INC	A
	LD	DE,MRZ80SD_STR_STNOMEDIA
	JR	Z,MRZ80SD_PRTSTATSTR1
	INC	A
	LD	DE,MRZ80SD_STR_STIOERR
	JR	Z,MRZ80SD_PRTSTATSTR1
	INC	A
	LD	DE,MRZ80SD_STR_STTO
	JR	Z,MRZ80SD_PRTSTATSTR1
	INC	A
	LD	DE,MRZ80SD_STR_STNOTRDY
	JR	Z,MRZ80SD_PRTSTATSTR1
	LD	DE,MRZ80SD_STR_STUNK
MRZ80SD_PRTSTATSTR1:
	CALL	WRITESTR
	POP	DE
	POP	AF
	RET
;
; PRINT DIAGNONSTIC PREFIX
;
MRZ80SD_PRTPREFIX:
	PUSH	AF
	CALL	NEWLINE
	PRTS("MRZ80SD$")
	LD	A,(IY+MRZ80SD_DEV)	; GET CURRENT DEVICE NUM
	CP	$FE			; NOT YET ASSIGNED?
	JR	Z,MRZ80SD_PRTPREFIX1	; SKIP DEV NUM IF SO
	CALL	PRTDECB
MRZ80SD_PRTPREFIX1:
	CALL	PC_COLON
	POP	AF
	RET
;
;=============================================================================
; STRING DATA
;=============================================================================
;
MRZ80SD_STR_STOK	.TEXT	"OK$"
MRZ80SD_STR_STNOMEDIA	.TEXT	"NO MEDIA$"
MRZ80SD_STR_STIOERR	.TEXT	"IO ERROR$"
MRZ80SD_STR_STTO	.TEXT	"TIMEOUT$"
MRZ80SD_STR_STNOTRDY	.TEXT	"NOT READY$"
MRZ80SD_STR_STUNK	.TEXT	"UNKNOWN ERROR$"
;
