; DATA STORAGE
;=============================================================================
;
MRZ80SD_CMDVAL	.DB	0		; PENDING COMMAND FOR IO FUNCTIONS
MRZ80SD_DSKBUF	.DW	0		; ACTIVE DISK BUFFER
;
MRZ80SD_DEVNUM	.DB	0		; TEMP DEVICE NUM USED DURING INIT
;
